create table if not exists public.wishes (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  message text not null check (char_length(message) between 1 and 500),
  created_at timestamptz not null default now()
);

alter table public.wishes enable row level security;

-- Los invitados pueden leer los mensajes publicados y enviar nuevos.
-- No se permite actualizar ni borrar mensajes desde el cliente público.
create policy "Anyone can read wishes"
on public.wishes for select
to anon, authenticated
using (true);

create policy "Anyone can add wishes"
on public.wishes for insert
to anon, authenticated
with check (
  char_length(trim(name)) between 1 and 80
  and char_length(trim(message)) between 1 and 500
);
